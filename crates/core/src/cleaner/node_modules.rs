//! Finds `node_modules` folders in projects you haven't touched for a while.
//! These are never pre-selected; `npm install` brings them back.

use std::path::{Path, PathBuf};

use serde::Serialize;

use crate::env::Env;
use crate::fsutil::{now_secs, path_size, to_unix, Cancel};
use crate::safety::{remove_checked, DeleteMode, DeleteReport, Guard};

/// Folders under home that never contain projects worth scanning.
const SKIP_DIRS: &[&str] = &["Library", "Applications", "Pictures", "Movies", "Music", "AppData"];
const MAX_DEPTH: usize = 8;

#[derive(Debug, Clone, Serialize)]
pub struct NodeModulesHit {
    pub path: String,
    pub project: String,
    pub bytes: u64,
    /// Latest change to any file directly in the project folder.
    pub last_touched: Option<i64>,
    pub stale: bool,
}

fn project_last_touched(project: &Path) -> Option<i64> {
    std::fs::read_dir(project)
        .ok()?
        .flatten()
        .filter(|e| e.file_name() != "node_modules")
        .filter_map(|e| e.metadata().ok()?.modified().ok().and_then(to_unix))
        .max()
}

/// Walk `roots` for project-level `node_modules` (never descending into them).
pub fn find(env: &Env, roots: &[PathBuf], stale_days: u32, cancel: &Cancel) -> Vec<NodeModulesHit> {
    let home = env.home.clone();
    let mut found = Vec::new();
    for root in roots {
        let home = home.clone();
        let walker = jwalk::WalkDir::new(root)
            .follow_links(false)
            .skip_hidden(true)
            .max_depth(MAX_DEPTH)
            .process_read_dir(move |_depth, dir, _state, children| {
                let at_home = dir == home.as_path();
                for child in children.iter_mut().flatten() {
                    let name = child.file_name.to_string_lossy();
                    let skip = name == "node_modules" || (at_home && SKIP_DIRS.contains(&name.as_ref()));
                    if skip {
                        child.read_children_path = None;
                    }
                }
            });
        for entry in walker {
            if cancel.is_cancelled() {
                return found_hits(found, stale_days);
            }
            let Ok(e) = entry else { continue };
            if e.file_type().is_dir() && e.file_name() == "node_modules" {
                let parent = e.parent_path().to_path_buf();
                if parent.join("package.json").exists() {
                    found.push(e.path());
                }
            }
        }
    }
    found_hits(found, stale_days)
}

fn found_hits(paths: Vec<PathBuf>, stale_days: u32) -> Vec<NodeModulesHit> {
    let cutoff = now_secs() - i64::from(stale_days) * 86_400;
    let mut hits: Vec<_> = paths
        .into_iter()
        .map(|p| {
            let project = p.parent().unwrap_or(&p).to_path_buf();
            let last = project_last_touched(&project);
            NodeModulesHit {
                bytes: path_size(&p, None, None),
                stale: last.is_some_and(|t| t < cutoff),
                last_touched: last,
                project: project.display().to_string(),
                path: p.display().to_string(),
            }
        })
        .collect();
    hits.sort_by_key(|a| std::cmp::Reverse(a.bytes));
    hits
}

pub fn remove(env: &Env, paths: &[String], mode: DeleteMode) -> DeleteReport {
    let guard = Guard::new(env);
    let mut report = DeleteReport::default();
    for p in paths.iter().map(PathBuf::from) {
        let is_project_modules = p.file_name().is_some_and(|n| n == "node_modules")
            && p.parent().is_some_and(|d| d.join("package.json").exists());
        if !is_project_modules {
            report.fail(&p, "not a project node_modules folder");
            continue;
        }
        match guard.check_user_file(&p) {
            Ok(checked) => remove_checked(&checked, mode, &mut report),
            Err(e) => report.fail(&p, e),
        }
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::env::Os;
    use std::fs;

    #[test]
    fn finds_project_node_modules_only() {
        let d = tempfile::tempdir().unwrap();
        let env = Env::sandboxed(d.path(), Os::Mac);
        let h = &env.home;
        for p in [
            "code/web/node_modules/react/index.js",
            "code/web/node_modules/react/node_modules/x/i.js",
            "code/web/package.json",
            "code/loose/node_modules/y.js",  // no package.json → ignored
            "Library/app/node_modules/z.js", // skipped folder
            ".npm/_npx/1/node_modules/a.js", // hidden → skipped
        ] {
            let f = h.join(p);
            fs::create_dir_all(f.parent().unwrap()).unwrap();
            fs::write(&f, b"x").unwrap();
        }
        let hits = find(&env, std::slice::from_ref(h), 30, &Cancel::new());
        assert_eq!(hits.len(), 1, "{hits:?}");
        assert!(hits[0].path.ends_with("code/web/node_modules"));
        assert!(!hits[0].stale, "just created");

        let r = remove(
            &env,
            &[hits[0].path.clone(), h.join("code/web").display().to_string()],
            DeleteMode::Permanent,
        );
        assert_eq!(r.removed.len(), 1);
        assert_eq!(r.failed.len(), 1);
        assert!(h.join("code/web/package.json").exists());
    }
}
